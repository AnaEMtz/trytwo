#!/usr/bin/env node
/*
 * Regenerates data/knowledge-base.js (used by the offline in-browser mode)
 * from data/knowledge-base.json. Run after editing the JSON:
 *
 *   node scripts/build-kb.js
 */
"use strict";
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "data");
const kb = JSON.parse(fs.readFileSync(path.join(dir, "knowledge-base.json"), "utf8"));

const ids = new Set();
const sourceIds = new Set(kb.sources.map((s) => s.id));
kb.chunks.forEach((c) => {
  if (ids.has(c.id)) throw new Error("Duplicate chunk id: " + c.id);
  ids.add(c.id);
  if (!sourceIds.has(c.source)) throw new Error("Chunk " + c.id + " has unknown source " + c.source);
  if (!c.title || !c.text) throw new Error("Chunk " + c.id + " needs a title and text");
});

fs.writeFileSync(
  path.join(dir, "knowledge-base.js"),
  "/* Generated by scripts/build-kb.js - do not edit by hand. */\nwindow.UNSE_KB = " + JSON.stringify(kb) + ";\n"
);
console.log(`Built data/knowledge-base.js: ${kb.chunks.length} passages from ${kb.sources.length} sources.`);
